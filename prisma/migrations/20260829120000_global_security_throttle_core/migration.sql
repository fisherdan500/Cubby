  INSERT INTO public."GlobalSecurityEvent" ("id","userId","eventType","outcome","operationId","incidentId","safeProjection","createdAt") VALUES ('gse_'||encode(gen_random_bytes(16),'hex'),scope_user_id,scope_event_type,scope_outcome,scope_operation_id,NULL,'{}',clock_timestamp());
END $$;

